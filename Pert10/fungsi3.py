def Kelpersegi(s):
    hasil= 4 * s
    print("Keliling Persegi ", hasil)

def Kelpersegipanjang(p, l):
    hasil= (p + l) * 2
    print("Keliling Persegi Panjang ", hasil)

def KelLingkaran(r):
    hasil= 2 * 3.14 * r
    print("Keliling lingkaran adalah ", hasil)

def Kelsegitiga(a, b, c):
    hasil= a + b + c
    print("Keliling Segitiga adalah ", hasil)